-- create table operator, copy data from ev_main, set foreign and primary key
DROP TABLE IF EXISTS dim_operator;
CREATE TABLE dim_operator (
	operator_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	operator TEXT);

INSERT INTO dim_operator (operator)
SELECT DISTINCT operator
FROM ev_main;

ALTER TABLE ev_main
ADD COLUMN operator_id INTEGER REFERENCES dim_operator (operator_id);

UPDATE ev_main
SET operator_id = dim_operator.operator_id
FROM dim_operator
WHERE ev_main.operator = dim_operator.operator;

-- create table charger, copy data from ev_main, set foreign and primary key
DROP TABLE IF EXISTS dim_charger;
CREATE TABLE dim_charger (
	charger_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	plug_type TEXT,
	current VARCHAR(3),
	price_type TEXT);

INSERT INTO dim_charger (plug_type, current, price_type)
SELECT DISTINCT plug_type, current, price_type
FROM ev_main
GROUP BY plug_type, current, price_type;

ALTER TABLE ev_main
ADD COLUMN charger_id INTEGER REFERENCES dim_charger (charger_id);

UPDATE ev_main
SET charger_id = dim_charger.charger_id
FROM dim_charger
WHERE ev_main.plug_type = dim_charger.plug_type
	AND ev_main.current = dim_charger.current
	AND ev_main.price_type = dim_charger.price_type;

