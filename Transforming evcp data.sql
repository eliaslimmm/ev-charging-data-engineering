WITH evcp_east AS (
SELECT LEFT(postal_code, 2) AS postal_prefix, COUNT(*) AS total_evcp
FROM ev_main
WHERE LEFT(postal_code, 2) IN ('42', '43', '44', '45', '46', '47', '48', '49', '50', '81', '51', '52')
GROUP BY postal_prefix
ORDER BY postal_prefix
)

SELECT SUM(total_evcp) AS total_evcp_east
FROM evcp_east

